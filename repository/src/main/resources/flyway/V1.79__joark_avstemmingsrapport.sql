CREATE TABLE JOARK_AVSTEMMING_KJORING
(
    ID                  BIGSERIAL PRIMARY KEY,
    STARTET_TIDSPUNKT    TIMESTAMPTZ NOT NULL,
    FULLFORT_TIDSPUNKT   TIMESTAMPTZ NOT NULL
);

CREATE TABLE JOARK_AVSTEMMING_RESULTAT
(
    KJORING_ID       BIGINT NOT NULL REFERENCES JOARK_AVSTEMMING_KJORING (ID),
    REKKEFOLGE       INTEGER NOT NULL,
    JOURNALPOST_ID   BIGINT NOT NULL,
    UTFALL           TEXT NOT NULL,
    KANAL            TEXT,
    DATO_OPPRETTET   DATE,
    PRIMARY KEY (KJORING_ID, REKKEFOLGE)
);
