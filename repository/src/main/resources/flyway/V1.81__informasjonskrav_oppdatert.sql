CREATE TABLE INFORMASJONSKRAV_OPPDATERT
(
    ID               BIGSERIAL PRIMARY KEY,
    JOURNALPOST_ID   BIGINT       NOT NULL,
    BEHANDLING_ID    BIGINT       NOT NULL REFERENCES BEHANDLING (ID),
    OPPDATERT        TIMESTAMP(3) NOT NULL,
    INFORMASJONSKRAV TEXT         NOT NULL,
    INFORMASJONSKRAV_INPUT JSONB
);

CREATE INDEX IDX_INFORMASJONSKRAV_OPPDATERT_JOURNALPOST_INFORMASJONSKRAV
    ON INFORMASJONSKRAV_OPPDATERT (JOURNALPOST_ID, INFORMASJONSKRAV, OPPDATERT DESC, ID DESC);

CREATE INDEX IDX_INFORMASJONSKRAV_OPPDATERT_BEHANDLING_ID
    ON INFORMASJONSKRAV_OPPDATERT (BEHANDLING_ID);
