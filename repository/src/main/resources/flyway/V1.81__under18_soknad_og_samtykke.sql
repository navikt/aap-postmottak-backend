CREATE TABLE UNDER18_SOKNAD
(
    ID                   BIGSERIAL PRIMARY KEY,
    BEHANDLING_ID        BIGINT NOT NULL REFERENCES BEHANDLING (ID),
    KILDE_JOURNALPOST_ID BIGINT NOT NULL UNIQUE
);

CREATE INDEX idx_under18_soknad_behandling_id ON UNDER18_SOKNAD (BEHANDLING_ID);

CREATE TABLE UNDER18_SAMTYKKEVURDERING
(
    ID                         BIGSERIAL PRIMARY KEY,
    BEGGE_FORELDRE_SAMTYKKET   BOOLEAN NOT NULL,
    SAMTYKKE_JOURNALPOST_IDER  BIGINT[] NOT NULL DEFAULT ARRAY[]::BIGINT[],
    VENT_OPPRETTET_TID         TIMESTAMP(3),
    OPPRETTET_TID               TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE UNDER18_SAMTYKKE_GRUNNLAG
(
    ID                     BIGSERIAL PRIMARY KEY,
    BEHANDLING_ID          BIGINT NOT NULL REFERENCES BEHANDLING (ID),
    SAMTYKKEVURDERING_ID   BIGINT NOT NULL UNIQUE REFERENCES UNDER18_SAMTYKKEVURDERING (ID),
    AKTIV                  BOOLEAN NOT NULL DEFAULT TRUE,
    OPPRETTET_TID          TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_under18_samtykke_grunnlag_behandling_id
    ON UNDER18_SAMTYKKE_GRUNNLAG (BEHANDLING_ID, ID);

CREATE UNIQUE INDEX uq_under18_samtykke_grunnlag_aktiv
    ON UNDER18_SAMTYKKE_GRUNNLAG (BEHANDLING_ID)
    WHERE AKTIV = TRUE;
